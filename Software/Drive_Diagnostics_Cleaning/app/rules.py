# Root files that must never be cleaned
_NECESSARY_ROOT_FILES = {
    "pagefile.sys": ("Virtual Memory", "Windows page file used as virtual memory. Required for system stability."),
    "hiberfil.sys": ("Hibernation", "Hibernation file. Required if hibernate/fast startup is enabled."),
    "swapfile.sys": ("Virtual Memory", "Windows swap file used by the system."),
    "bootmgr": ("Boot", "Windows boot manager. Required to start the OS."),
}


def _norm(path: str) -> str:
    return os.path.normpath(path).replace("/", "\\").lower().rstrip("\\")


def _drive_root(path: str) -> str:
    drive, _ = os.path.splitdrive(os.path.abspath(path))
    return (drive + "\\").lower()


def _rel_to_drive(path: str) -> str:
    full = _norm(path)
    root = _drive_root(path)
    if full.startswith(root.rstrip("\\")):
        rel = full[len(root) :]
        return rel.lstrip("\\")
    return full


def classify_path(path: str, is_directory: bool = False) -> Optional[RuleMatch]:
    """
    Classify a path. Returns None if no specific rule applies
    (caller may skip or mark as Review for large unknown items).
    """
    full = _norm(path)
    rel = _rel_to_drive(path)
    name = os.path.basename(full)

    # Root-level protected files
    if name in _NECESSARY_ROOT_FILES and "\\" not in rel:
        cat, reason = _NECESSARY_ROOT_FILES[name]
        return RuleMatch(Classification.NECESSARY, reason, cat, False)

    # Necessary prefixes
    for prefix, category, reason in _NECESSARY_PREFIXES:
        if rel == prefix or rel.startswith(prefix + "\\"):
            # Exception: allow known unnecessary subpaths under Windows
            override = _check_unnecessary(rel)
            if override:
                return override
            return RuleMatch(Classification.NECESSARY, reason, category, False)

    # Unnecessary targets
    unn = _check_unnecessary(rel)
    if unn:
        return unn

    # Users\<name>\...
    m = re.match(r"^users\\[^\\]+\\(.+)$", rel)
    if m:
        user_rel = m.group(1)
        for prefix, category, reason, safe in _USER_UNNECESSARY:
            if prefix.endswith("thumbcache_"):
                # Match thumbcache_*.db files under Explorer
                base = prefix[: -len("thumbcache_")]
                name = user_rel.rsplit("\\", 1)[-1]
                if user_rel.startswith(base) and name.startswith("thumbcache_"):
                    return RuleMatch(Classification.UNNECESSARY, reason, category, safe, True)
            elif user_rel == prefix or user_rel.startswith(prefix + "\\"):
                return RuleMatch(Classification.UNNECESSARY, reason, category, safe, True)

        for suffix, category, reason in _USER_NECESSARY_SUFFIXES:
            # match folder name at this level or deeper known profile folders
            parts = user_rel.split("\\")
            if parts and parts[0] == suffix:
                # Downloads → Review (not auto-clean)
                if suffix == "downloads":
                    return RuleMatch(Classification.REVIEW, reason, category, False, True)
                return RuleMatch(Classification.NECESSARY, reason, category, False, True)

        if user_rel.startswith("appdata\\"):
            return RuleMatch(
                Classification.REVIEW,
                "Application data may contain settings, licenses, or caches. Review before removing.",
                "AppData",
                False,
                True,
            )

    # Top-level Users folder itself
    if rel == "users" or re.match(r"^users\\[^\\]+$", rel):
        return RuleMatch(
            Classification.NECESSARY,
            "User profile root. Contains personal and application data.",
            "User Profiles",
            False,
            True,
        )

    # Top-level Windows folder (already partially covered)
    if rel == "windows":
        return RuleMatch(
            Classification.NECESSARY,
            "Windows operating system folder. Do not remove.",
            "System Critical",
            False,
            True,
        )

    return None


def _check_unnecessary(rel: str) -> Optional[RuleMatch]:
    for prefix, category, reason, safe in _UNNECESSARY_TARGETS:
        if rel == prefix or rel.startswith(prefix + "\\"):
            return RuleMatch(Classification.UNNECESSARY, reason, category, safe, True)
    return None


def is_protected_path(path: str) -> bool:
    """Hard block list for cleaner — never delete these."""
    match = classify_path(path)
    if match and match.classification == Classification.NECESSARY:
        return True
    rel = _rel_to_drive(path)
    name = os.path.basename(_norm(path))
    if name in _NECESSARY_ROOT_FILES and "\\" not in rel:
        return True
    critical = (
        r"windows\system32",
        r"windows\syswow64",
        r"windows\winsxs",
        r"windows\boot",
        r"system volume information",
        r"recovery",
        r"program files",
        r"program files (x86)",
    )
    for c in critical:
        if rel == c or rel.startswith(c + "\\"):
            return True
    return False
