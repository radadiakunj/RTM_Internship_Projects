from typing import Optional

from .models import Classification


@dataclass(frozen=True)
class RuleMatch:
    classification: Classification
    reason: str
    category: str
    safe_to_delete: bool
    # If True, treat as a known target folder (scan its children for size)
    is_target_root: bool = False


